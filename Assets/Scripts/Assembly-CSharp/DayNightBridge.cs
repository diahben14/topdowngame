using System.Collections;
using UnityEngine;
using UnityEngine.AI;
using UnityEngine.Serialization;

[SelectionBase]
public class DayNightBridge : MonoBehaviour
{
	public enum DayNight
	{
		DAY = 0,
		NIGHT = 1
	}

	public enum BridgeOrBarrier
	{
		BRIDGE = 0,
		BARRIER = 1,
		DISABLE_GROUP = 2
	}

	[SerializeField]
	[FormerlySerializedAs("traversableDuring")]
	private DayNight dayOrNight;

	[SerializeField]
	private BridgeOrBarrier bridgeOrBarrier;

	[SerializeField]
	[Tooltip("When ON, the navblocker will always be on, regardless of day/night")]
	protected bool animatable_alwaysNavBlock;

	[HideInInspector]
	protected NavMeshObstacle autogeneratedNavMeshObstacle;

	protected NavMeshObstacle[] navMeshObstacles;

	protected MeshRenderer[] meshRenderers;

	protected Collider[] colliders;

	private void OnValidate()
	{
		if (!Application.isPlaying && base.gameObject.activeInHierarchy)
		{
			StartCoroutine(validation());
		}
	}

	private IEnumerator validation()
	{
		yield return new WaitForEndOfFrame();
		if (bridgeOrBarrier == BridgeOrBarrier.BARRIER)
		{
			NavMeshModifier navMeshModifier = GetComponent<NavMeshModifier>();
			if (navMeshModifier == null)
			{
				navMeshModifier = base.gameObject.AddComponent<NavMeshModifier>();
			}
			navMeshModifier.ignoreFromBuild = true;
		}
		else
		{
			NavMeshModifier component = GetComponent<NavMeshModifier>();
			if (component != null)
			{
				Object.DestroyImmediate(component);
			}
		}
		NavMeshObstacle navMeshObstacle = GetComponentInChildren<NavMeshObstacle>();
		if (bridgeOrBarrier != BridgeOrBarrier.DISABLE_GROUP)
		{
			if (navMeshObstacle == null)
			{
				GameObject obj = new GameObject("nav mesh blocker");
				obj.transform.parent = base.transform;
				obj.transform.localPosition = Vector3.zero;
				navMeshObstacle = (autogeneratedNavMeshObstacle = obj.AddComponent<NavMeshObstacle>());
			}
			navMeshObstacle.enabled = false;
			navMeshObstacle.carving = true;
		}
		else if (navMeshObstacle != null && navMeshObstacle == autogeneratedNavMeshObstacle)
		{
			navMeshObstacle.enabled = false;
		}
	}

	private void Awake()
	{
		cacheChildComponents();
		updateActiveness();
	}

	private void OnDestroy()
	{
	}

	private void onStateChange()
	{
		updateActiveness();
	}

	private void cacheChildComponents()
	{
		navMeshObstacles = GetComponentsInChildren<NavMeshObstacle>();
		meshRenderers = GetComponentsInChildren<MeshRenderer>();
		colliders = GetComponentsInChildren<Collider>();
	}

	private void FixedUpdate()
	{
		updateActiveness();
	}

	private void updateActiveness()
	{
		bool flag = false;
		bool flag2 = dayOrNight == DayNight.NIGHT;
		if (bridgeOrBarrier == BridgeOrBarrier.DISABLE_GROUP)
		{
			base.gameObject.SetActive(flag == flag2);
			return;
		}
		bool flag3 = bridgeOrBarrier == BridgeOrBarrier.BARRIER;
		for (int i = 0; i < navMeshObstacles.Length; i++)
		{
			navMeshObstacles[i].enabled = (flag2 ^ flag3 ^ flag) || animatable_alwaysNavBlock;
		}
		for (int j = 0; j < meshRenderers.Length; j++)
		{
			meshRenderers[j].enabled = flag == flag2;
		}
		for (int k = 0; k < colliders.Length; k++)
		{
			colliders[k].enabled = flag == flag2;
		}
	}
}
